/**
 * Get a national variant glyph by Unicode codepoint.
 * Returns a 12×10 pixel array (doubled horizontally from 6×10), or null if not available.
 */
export function getNationalGlyph(codepoint: number): Uint8Array | null {
  const rows = NATIONAL_GLYPHS[codepoint];
  if (!rows) return null;

  const pixels = new Uint8Array(12 * 10);
  for (let y = 0; y < 10; y++) {
    const rowBits = rows[y];
    for (let srcX = 0; srcX < 6; srcX++) {
      const bit = (rowBits >> (5 - srcX)) & 1;
      const dstX = srcX * 2;
      pixels[y * 12 + dstX] = bit;
      pixels[y * 12 + dstX + 1] = bit;
    }
  }
  return pixels;
}

/**
 * Check if a codepoint has a national variant glyph available.
 */
export function hasNationalGlyph(codepoint: number): boolean {
  return codepoint in NATIONAL_GLYPHS;
}
