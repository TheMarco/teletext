/**
 * Decode a Hamming 8/4 encoded byte.
 * Returns the 4-bit data value (0-15), or -1 if uncorrectable.
 */
export function hammingDecode84(byte: number): number {
  const val = HAMMING_8_4_TABLE[byte & 0xFF];
  return val === 0xFF ? -1 : val;
}

/**
 * Strip parity bit from a 7-bit data byte.
 * Teletext data bytes use bit 7 as an odd parity bit.
 */
export function stripParity(byte: number): number {
  return byte & 0x7F;
}
